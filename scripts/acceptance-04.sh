#!/bin/sh
# Step 04 acceptance. Run from the project root:  sh scripts/acceptance-04.sh
# Every block is a signoff item from docs/steps/04-pdfsign.md.
set -e
D=$(mktemp -d)
cleanup() {
  rm -rf "$D"
  rm -f ./signsrv
}
trap cleanup EXIT

cat > "$D/dev.conf" <<EOF
listen=127.0.0.1:8090
public_url=http://127.0.0.1:8090
dev=true
db=$D/signsrv.db
storage_dir=$D/storage
keystore_dir=$D/keystore
outbox_dir=$D/outbox
log_path=$D/signsrv.jsonl
keystore_pass=dev-keystore-passphrase-that-is-long
admin_password=dev-password-change-me
smtp_host=127.0.0.1
mail_from=signsrv@example.test
EOF

echo "== vendored patch present =="
# The fix in vendor/github.com/digitorus/pdfsign/sign/pdfvisualsignature.go
# (keep an indirect page entry as a reference) is required: without it every
# signature the library adds fails its own DocMDP check. vendor/ is
# regenerated by `go mod vendor`, which wipes the edit, so the patch file is
# the only place it is kept. If this line fails, run scripts/apply-patches.sh.
patch -p1 --reverse --dry-run --quiet < patches/pdfsign-page-references.patch \
  && echo "  pdfsign page-reference patch is applied"

echo "== build offline from vendor =="
GOFLAGS=-mod=vendor GOPROXY=off go build -o "$D/signsrv" ./cmd/signsrv
GOFLAGS=-mod=vendor GOPROXY=off go build ./internal/signpdf
echo "  ok"

echo "== vet and gofmt =="
go vet -mod=vendor ./cmd/signsrv ./internal/signpdf
test -z "$(gofmt -l ./cmd ./internal)" && echo "  clean"

echo "== unit tests: the acceptance list of 04, on testdata/sample1.pdf =="
go test -mod=vendor -count=1 ./internal/signpdf 2>&1 | grep -v '^{"time"'

echo "== sign-selftest: exit 0, valid, 4 signatures =="
cp testdata/sample1.pdf "$D/in.pdf"
"$D/signsrv" sign-selftest -config "$D/dev.conf" "$D/in.pdf" "$D/out.pdf" > "$D/report.json" 2>"$D/report.err"
test -z "$(cat "$D/report.err")" && echo "  no stderr"
jq -r '.valid' "$D/report.json" | grep -q true && echo "  valid=true"
n=$(jq -r '.signers | length' "$D/report.json")
test "$n" = "4" && echo "  signers: $n"
jq -r '[.signers[0].Name, (.signers[0].Timestamp|tostring)] | join(" ts=")' "$D/report.json" \
  | sed 's/^/  first signer: /'
test "$(jq -r '.signers[0].Name' "$D/report.json")" = "signsrv" && echo "  first signer is the certification"
test -s "$D/out.pdf" && echo "  out.pdf written: $(wc -c < "$D/out.pdf") bytes"
cert=$(jq -r '.certified_bytes' "$D/report.json")
echo "  certified bytes: $cert, output: $(wc -c < "$D/out.pdf")  (output is an incremental update)"

echo "== keystore: CA key encrypted at rest, 0600, passphrase not in the log =="
test -f "$D/keystore/ca.key" || { echo "  ca.key missing"; exit 1; }
mode=$(stat -c '%a' "$D/keystore/ca.key")
test "$mode" = "600" && echo "  ca.key mode $mode"
if grep -q "BEGIN PRIVATE KEY" "$D/keystore/ca.key"; then echo "  ca.key is plaintext"; exit 1; else
  echo "  ca.key carries no plaintext private key"
fi
if grep -q "dev-keystore-passphrase" "$D/signsrv.jsonl" 2>/dev/null; then echo "  passphrase in log"; exit 1
else echo "  passphrase absent from the log"; fi
if grep -q "BEGIN PRIVATE KEY" "$D/out.pdf"; then echo "  private key in the signed file"; exit 1
else echo "  no private key in the signed file"; fi

echo "== checkpdf: the signed file verifies =="
"$D/signsrv" checkpdf -config "$D/dev.conf" "$D/out.pdf" > "$D/check.json"
jq -r '.valid' "$D/check.json" | grep -q true && echo "  valid=true"
test "$(jq -r '.signers | length' "$D/check.json")" = "4" && echo "  4 signers"

echo "== tampered document: verify fails, errors non-empty =="
cp "$D/out.pdf" "$D/tampered.pdf"
printf 'x' | dd of="$D/tampered.pdf" bs=1 seek=40000 count=1 conv=notrunc status=none
code=0; "$D/signsrv" checkpdf -config "$D/dev.conf" "$D/tampered.pdf" > "$D/tampered.json" 2>&1 || code=$?
test "$code" != 0 && echo "  exit $code (non-zero)"
jq -r '.valid' "$D/tampered.json" | grep -q false && echo "  valid=false"
test "$(jq -r '.errors | length' "$D/tampered.json")" != "0" && echo "  errors reported"

echo "== missing TSA: clear error, no silent fallback =="
code=0; "$D/signsrv" sign-selftest -config "$D/dev.conf" -tsa - "$D/in.pdf" > "$D/notsa.out" 2>&1 || code=$?
test "$code" != 0 && echo "  exit $code (non-zero)"
grep -qi "TSA" "$D/notsa.out" && echo "  says: $(head -1 "$D/notsa.out")"

echo "== all step 04 checks passed =="
